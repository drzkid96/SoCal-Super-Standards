import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {makeCatalog, scanLines, pdfLines, pdfSheetLabel, pastedPages, joinCalloutLines} from '../public/js/sign-import-parser.mjs';
const catalog=makeCatalog(JSON.parse(readFileSync(new URL('../public/data/sign-block-options.json',import.meta.url))));
const scan=lines=>new Map(scanLines(lines,catalog).map(row=>[row.key,row]));
const sample=scan(['R1-1, W48 (2) (CA), R1-1','R2-1 (25 MPH); R2-1 35 MPH','R3-7(R)(MOD); R3-7(LT)(MOD); R3-7(RT)(MOD)','W16-7P(UNKNOWN); W1-5R; W1-5L; W19-999A; W16-7P(L/R)','R2-1']);
assert.equal(sample.get('W48(2)(CA)').selected,'official-callout-w48-2ca');
assert.equal(sample.get('R1-1').count,2);
assert.equal(sample.get('R2-1(25)').selected,'3346-signs-1-13-10980d1');
assert.equal(sample.get('R2-1(35)').status,'ambiguous');assert.equal(sample.get('R2-1').status,'ambiguous');
for(const k of ['W16-7P(UNKNOWN)','W19-999A','W16-7P(L/R)'])assert.equal(sample.get(k).status,'unmatched');
for(const k of ['W1-5R','W1-5L','R3-7(R)(MOD)','R3-7(LT)(MOD)','R3-7(RT)(MOD)'])assert(sample.has(k));
for(const row of sample.values())if(row.status!=='matched')assert.equal(row.selected,'');
const run=(str,x,y,width,angle=0)=>({str,width,transform:[10*Math.cos(angle),10*Math.sin(angle),-10*Math.sin(angle),10*Math.cos(angle),x,y]});
assert.deepEqual(pdfLines([run('R',20,25,6),run('1-',26,25,8),run('1',34,25,5),run('R2-',260,25,14),run('1',21,40,5)]),['1','R1-1','R2-']);
assert.deepEqual(pdfLines([run('W',10,10,8,Math.PI/2),run('48(2)(CA)',10,18,42,Math.PI/2)]),['W48(2)(CA)']);
assert.deepEqual(pastedPages('SHEET: SS-1\nR1-1\n--- SHEET SS-2 ---\nR1-1\fW48(2)(CA)').map(r=>r.label),['SS-1','SS-2','Sheet 3']);
assert(!scan(pdfLines([run('R2-',20,30,10),run('1',275,30,3)])).has('R2-1'));
const position=(text,left,right,baseline)=>({text,left,right,baseline,height:10,turn:0});
assert.deepEqual(joinCalloutLines([position('R10-15',90,130,100),position('R10-11',20,60,100),position('(MOD)',92,128,87)]),['R10-15(MOD)','R10-11']);
assert.deepEqual(joinCalloutLines([position('R10-15',90,130,100),position('(MOD)',200,236,87)]),['R10-15','(MOD)']);
assert.equal(scan(['BUS','LANE','ONLY']).size,0);
assert.equal(scan(['R1-1','(MOD)']).get('R1-1').selected,'');
assert.equal(pdfSheetLabel('[4] 4 SS-2',4),'SS-2');
assert.equal(pdfSheetLabel('[4] 7 EXISTING',4),'[4] 7 EXISTING');
console.log('Exact designation, ambiguous artwork, hand, MOD, speed, W48, sheet breaks, separated columns and rotated runs passed.');
