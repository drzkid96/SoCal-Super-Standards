"""Elongated pavement-marking alphabet (A-Z, 0-9) for the custom pavement text block.

Source: FHWA Standard Highway Signs and Markings, Pavement Markings chapter (Pavement.pdf), pages
10-1 to 10-7. Each character is one filled vector shape; white fills are its counters (holes). The
shapes are traced exactly, normalized to a cap height of 1 with the baseline at 0, and written to
public/js/pavement-alphabet.js, which the block editor and the library worker load.

  python3 pipeline/pavement_alphabet.py [Pavement.pdf]   (downloads the PDF when no path is given)
"""
import hashlib
import json
import sys
import urllib.request
from pathlib import Path

import pymupdf
from shapely.geometry import Polygon
from shapely.geometry.polygon import orient

URL = 'https://mutcd.fhwa.dot.gov/SHSe/Pavement.pdf'
SHA = 'a7956afb548185a73e33ee31c10c84fdf4cdbe8556586d73b76e7f45181219e0'
OUT = Path('public/js/pavement-alphabet.js')
# characters in drawing order on pages 10-1 to 10-7 (checked against the drawings)
ORDER = 'CABDE' 'HFIJGK' 'ONLMP' 'SQTRU' 'XVYWZ' '52314' '86907'


def bezier(p0, p1, p2, p3, n=16):
    pts = []
    for i in range(1, n + 1):
        t = i / n
        u = 1 - t
        pts.append((u ** 3 * p0.x + 3 * u * u * t * p1.x + 3 * u * t * t * p2.x + t ** 3 * p3.x,
                    u ** 3 * p0.y + 3 * u * u * t * p1.y + 3 * u * t * t * p2.y + t ** 3 * p3.y))
    return pts


def shape(drawing):
    subs, cur, last = [], [], None
    for it in drawing['items']:
        if it[0] == 're':
            r = it[1]
            subs.append([(r.x0, r.y0), (r.x1, r.y0), (r.x1, r.y1), (r.x0, r.y1)])
            continue
        a = it[1]
        if last is None or abs(a.x - last.x) > 0.01 or abs(a.y - last.y) > 0.01:
            if len(cur) > 2:
                subs.append(cur)
            cur = [(a.x, a.y)]
        if it[0] == 'l':
            cur.append((it[2].x, it[2].y))
            last = it[2]
        elif it[0] == 'c':
            cur += bezier(it[1], it[2], it[3], it[4])
            last = it[4]
    if len(cur) > 2:
        subs.append(cur)
    out = None
    for s in subs:                       # even-odd fill
        p = Polygon(s).buffer(0)
        out = p if out is None else out.symmetric_difference(p)
    return out


def glyphs(pdf):
    doc = pymupdf.open(pdf)
    found = []
    for page in range(7):
        dark, white = [], []
        for d in doc[page].get_drawings():
            if d['type'] in ('f', 'fs'):
                (white if d['fill'][0] > 0.9 else dark).append(shape(d))
        for w in white:
            i = next(i for i, g in enumerate(dark) if g.contains(w.centroid))
            dark[i] = dark[i].difference(w)
        found += dark
    if len(found) != len(ORDER):
        raise ValueError(f'expected {len(ORDER)} characters, found {len(found)}')
    return dict(zip(ORDER, found))


def build(pdf):
    data = Path(pdf).read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA:
        raise ValueError('Pavement.pdf changed; check the character order before publishing')
    shapes = glyphs(pdf)
    flat = [shapes[c] for c in 'EFHIKLMNTXZ']           # letters with flat top and bottom set the cap height
    cap = sum(g.bounds[3] - g.bounds[1] for g in flat) / len(flat)
    out = {}
    for ch, g in sorted(shapes.items()):
        x0, y0, x1, y1 = g.bounds
        # rows: the bottom of a flat letter in the same row is the baseline (PDF y runs down)
        row = [f for f in flat if abs(f.bounds[1] - y0) < 30 or abs(f.bounds[3] - y1) < 30]
        base = max((f.bounds[3] for f in row), default=y1)
        rings = []
        for part in getattr(g, 'geoms', [g]):
            part = orient(part.simplify(0.05), 1.0)
            for ring in [part.exterior, *part.interiors]:
                rings.append([[round((x - x0) / cap, 4), round((base - y) / cap, 4)] for x, y in ring.coords[:-1]])
        top = max(y for r in rings for _, y in r)
        if top < 0.95:      # the FHWA drawing of U stops 4 grid squares short; its straight stems run to cap height
            rings = [[[x, round(y + 1 - top, 4) if y > 0.5 else y] for x, y in r] for r in rings]
        out[ch] = {'w': round((x1 - x0) / cap, 4), 'rings': rings}
    head = ('// FHWA elongated pavement-marking alphabet (Standard Highway Signs, Pavement Markings 10-1 to 10-7).\n'
            '// Generated by pipeline/pavement_alphabet.py. Cap height 1, baseline 0; w is the letter width;\n'
            '// rings are filled with the even-odd rule (counters are holes).\n')
    OUT.write_text(head + 'self.SSSPavementAlphabet = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    return out


if __name__ == '__main__':
    src = sys.argv[1] if len(sys.argv) > 1 else None
    if not src:
        src = '/tmp/Pavement.pdf'
        urllib.request.urlretrieve(URL, src)
    g = build(src)
    print(len(g), 'characters written to', OUT, f'({OUT.stat().st_size // 1024} KB)')
